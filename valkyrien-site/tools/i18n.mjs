/*
 * Static i18n generator.
 * templates/pages/**.html + templates/partials/*.html + locales/<code>.json
 *   -> src/<page>.html (default locale) and src/<code>/<page>.html (others)
 * Generated pages are build artefacts (gitignored): edit templates and locales only.
 *
 * Template syntax
 *   {{t:key}}                         translated string (HTML allowed); missing key = build error
 *   <!-- @include partials/x.html a="..." current="home" -->
 *   {{lang}} {{htmlLang}} {{base}}    locale data;  {{i18nHead}} hreflang + canonical;  {{langSwitcher}}
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

export const SITE = 'https://valkyrien.co.uk';
export const LOCALES = [
  { code: 'en', htmlLang: 'en-GB', base: '', name: 'English', short: 'EN' },
  { code: 'it', htmlLang: 'it', base: '/it', name: 'Italiano', short: 'IT' },
  { code: 'fr', htmlLang: 'fr', base: '/fr', name: 'Français', short: 'FR' },
  { code: 'es', htmlLang: 'es', base: '/es', name: 'Español', short: 'ES' },
  { code: 'de', htmlLang: 'de', base: '/de', name: 'Deutsch', short: 'DE' },
];
export const PAGES = [
  { tpl: 'index.html', route: '/' },
  { tpl: 'who-we-are/index.html', route: '/who-we-are/' },
  { tpl: 'compliance/index.html', route: '/compliance/' },
  { tpl: 'engage/index.html', route: '/engage/' },
];
const ROUTES = PAGES.map((p) => p.route);

export function generate(srcDir) {
  const tplDir = resolve(srcDir, 'templates');
  const dicts = Object.fromEntries(LOCALES.map((l) => [l.code, JSON.parse(readFileSync(resolve(srcDir, 'locales', `${l.code}.json`), 'utf8'))]));
  checkKeys(dicts);

  const inputs = {};
  for (const loc of LOCALES) {
    for (const page of PAGES) {
      let html = includes(readFileSync(resolve(tplDir, 'pages', page.tpl), 'utf8'), tplDir);
      html = html
        .replaceAll('{{i18nHead}}', i18nHead(page, loc))
        .replaceAll('{{lang}}', loc.code)
        .replaceAll('{{htmlLang}}', loc.htmlLang);
      html = html.replace(/\{\{t:([\w.-]+)\}\}/g, (_, key) => {
        const v = dicts[loc.code][key];
        if (v === undefined) throw new Error(`[i18n] missing key "${key}" in ${loc.code}.json (${page.tpl})`);
        return v;
      });
      html = localiseLinks(html, loc);
      // after localiseLinks: switcher hrefs already point at each locale and must not be re-prefixed
      html = html.replaceAll('{{langSwitcher}}', langSwitcher(page, loc, dicts[loc.code]));
      const leftover = html.match(/\{\{[^}]+\}\}/);
      if (leftover) throw new Error(`[i18n] unresolved token ${leftover[0]} in ${loc.code}/${page.tpl}`);

      const out = resolve(srcDir, loc.base.slice(1), page.tpl);
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, `<!-- GENERATED by tools/i18n.mjs from templates/pages/${page.tpl} (${loc.code}). Do not edit. -->\n${html}`);
      inputs[`${loc.code}-${page.tpl.replace(/\/?index\.html$/, '') || 'home'}`] = out;
    }
  }
  return inputs;
}

function includes(html, tplDir) {
  return html.replace(/<!--\s*@include\s+(\S+)((?:\s+\w+="[^"]*")*)\s*-->/g, (_, file, rawArgs) => {
    let out = readFileSync(resolve(tplDir, file), 'utf8');
    for (const [, k, v] of rawArgs.matchAll(/(\w+)="([^"]*)"/g)) {
      out = out.replaceAll(`{{${k}}}`, v);
      if (k === 'current') out = out.replaceAll(`data-nav="${v}"`, `data-nav="${v}" aria-current="page"`);
    }
    return includes(out, tplDir).replace(/\{\{(?!t:|i18nHead|langSwitcher|lang\b|htmlLang)\w+\}\}/g, '');
  });
}

// Internal page links get the locale prefix; assets, PDFs and external links are shared.
function localiseLinks(html, loc) {
  if (!loc.base) return html;
  return html.replace(/href="(\/[^"]*)"/g, (m, href) => {
    const path = href.split('#')[0];
    return ROUTES.includes(path) ? `href="${loc.base}${href}"` : m;
  });
}

function i18nHead(page, loc) {
  const url = (l) => `${SITE}${l.base}${page.route}`;
  return [
    `<link rel="canonical" href="${url(loc)}">`,
    ...LOCALES.map((l) => `<link rel="alternate" hreflang="${l.htmlLang}" href="${url(l)}">`),
    `<link rel="alternate" hreflang="x-default" href="${url(LOCALES[0])}">`,
  ].join('\n  ');
}

function langSwitcher(page, loc, dict) {
  const items = LOCALES.map((l) => {
    const cur = l.code === loc.code ? ' aria-current="true"' : '';
    return `<li><a class="lang-switch__link" href="${l.base}${page.route}" hreflang="${l.htmlLang}" lang="${l.htmlLang}"${cur}><span class="lang-switch__code">${l.short}</span>${l.name}</a></li>`;
  }).join('\n          ');
  return `<details class="lang-switch" data-lang-switch>
      <summary class="lang-switch__toggle">
        <svg class="icon" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><circle cx="12" cy="12" r="9"/><path d="M3 12h18M12 3c2.5 2.7 3.8 5.7 3.8 9s-1.3 6.3-3.8 9c-2.5-2.7-3.8-5.7-3.8-9S9.5 5.7 12 3z"/></svg>
        <span class="sr-only">${dict['lang.label']}: </span><span>${loc.short}</span>
        <svg class="icon lang-switch__chevron" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="M7 10l5 5 5-5"/></svg>
      </summary>
      <ul class="lang-switch__list">
          ${items}
      </ul>
    </details>`;
}

function checkKeys(dicts) {
  const ref = Object.keys(dicts[LOCALES[0].code]);
  for (const { code } of LOCALES.slice(1)) {
    const keys = new Set(Object.keys(dicts[code]));
    const missing = ref.filter((k) => !keys.has(k));
    const extra = [...keys].filter((k) => !ref.includes(k));
    if (missing.length || extra.length) throw new Error(`[i18n] ${code}.json out of sync. missing: ${missing.join(', ') || '-'} | extra: ${extra.join(', ') || '-'}`);
  }
}
